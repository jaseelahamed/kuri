import React, { useState } from 'react';
import { X, UserPlus, Mail, Phone, User, CheckCircle2, AlertCircle, Copy, Check, Key } from 'lucide-react';
import { translations } from '../translations';
import { API_BASE_URL } from '../config';

export default function AddMemberModal({ groupId, groupName, lang = 'en', onClose, onMemberAdded }) {
  const t = translations[lang] || translations.en;
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [phone, setPhone] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);

  const token = localStorage.getItem('kuri_token');

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const res = await fetch(`${API_BASE_URL}/api/kuri/${groupId}/members`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`,
        },
        body: JSON.stringify({ name, email, phone }),
      });

      const data = await res.json();
      if (!res.ok) throw new Error(data.message || 'Failed to add member');

      setResult(data);
      if (onMemberAdded) onMemberAdded(data.member);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleCopyPassword = () => {
    if (result?.generatedPassword) {
      navigator.clipboard.writeText(result.generatedPassword);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 dark:bg-black/80 backdrop-blur-sm">
      <div className="relative w-full max-w-md glass-modal rounded-3xl p-5 sm:p-6 text-slate-800 dark:text-white shadow-2xl border border-slate-200 dark:border-slate-800 transition-colors max-h-[92vh] overflow-y-auto">
        <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-4">
          <div className="flex items-center gap-3">
            <div className="p-2.5 rounded-xl bg-indigo-50 dark:bg-indigo-600/30 text-indigo-600 dark:text-indigo-400 border border-indigo-200 dark:border-indigo-500/30">
              <UserPlus className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-lg font-bold text-slate-900 dark:text-white">{t.addMemberTitle}</h2>
              <p className="text-xs text-slate-500 dark:text-slate-400">{groupName}</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-slate-700 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {error && (
          <div className="my-4 p-3 bg-rose-500/15 border border-rose-500/30 rounded-xl flex items-center gap-2 text-rose-600 dark:text-rose-300 text-sm">
            <AlertCircle className="w-4 h-4 flex-shrink-0" />
            <span>{error}</span>
          </div>
        )}

        {result ? (
          <div className="py-4 text-center space-y-4">
            <div className="w-14 h-14 rounded-full bg-emerald-500/20 text-emerald-500 dark:text-emerald-400 border border-emerald-500/30 flex items-center justify-center mx-auto">
              <CheckCircle2 className="w-7 h-7" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900 dark:text-white">{t.memberAddedSuccess}</h3>
              <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">{t.autoGeneratedSubtitle}</p>
            </div>

            {/* Kuri Number Badge */}
            <div className="p-4 rounded-2xl bg-indigo-50 dark:bg-indigo-950/40 border border-indigo-200 dark:border-indigo-500/40 max-w-xs mx-auto">
              <div className="text-xs text-indigo-600 dark:text-indigo-300 font-semibold uppercase tracking-wider">
                {t.kuriNumberBadgeLabel}
              </div>
              <div className="text-4xl font-extrabold text-indigo-600 dark:text-indigo-400 tracking-widest mt-1">
                #{result.member.kuriNumber}
              </div>
              <div className="text-sm font-medium text-slate-700 dark:text-slate-200 mt-1">{result.member.name}</div>
            </div>

            {/* Credentials / Password Section */}
            {result.generatedPassword ? (
              <div className="p-3.5 rounded-2xl bg-slate-50 dark:bg-slate-900/80 border border-slate-200 dark:border-slate-800 text-left space-y-2">
                <div className="flex items-center gap-2 text-xs font-bold text-slate-700 dark:text-slate-200">
                  <Key className="w-4 h-4 text-amber-500" />
                  <span>{t.loginCredentialsTitle}</span>
                </div>

                <div className="text-xs text-slate-600 dark:text-slate-400 space-y-1">
                  <div>
                    <span className="font-semibold text-slate-500">{t.emailAddress}:</span>{' '}
                    <span className="font-medium text-slate-800 dark:text-slate-200">{result.member.email}</span>
                  </div>
                  <div className="flex items-center justify-between gap-2 pt-1">
                    <div>
                      <span className="font-semibold text-slate-500 block text-[11px]">{t.tempPasswordLabel}</span>
                      <span className="font-mono font-bold text-indigo-600 dark:text-indigo-400 text-sm tracking-wider">
                        {result.generatedPassword}
                      </span>
                    </div>
                    <button
                      type="button"
                      onClick={handleCopyPassword}
                      className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-indigo-100 dark:bg-indigo-600/30 text-indigo-700 dark:text-indigo-300 text-xs font-semibold hover:bg-indigo-200 dark:hover:bg-indigo-600/50 transition"
                    >
                      {copied ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
                      <span>{copied ? t.copied : t.copyPassword}</span>
                    </button>
                  </div>
                </div>

                <p className="text-[11px] text-slate-500 dark:text-slate-400 pt-1 border-t border-slate-200 dark:border-slate-800">
                  {t.loginCredentialsDesc}
                </p>
              </div>
            ) : (
              <div className="p-3 rounded-xl bg-slate-100 dark:bg-slate-800/60 text-slate-600 dark:text-slate-300 text-xs text-left">
                {t.existingAccountNotice}
              </div>
            )}

            {result.emailSent ? (
              <div className="p-2.5 rounded-xl bg-emerald-50 dark:bg-emerald-950/30 border border-emerald-200 dark:border-emerald-500/20 text-emerald-700 dark:text-emerald-300 text-xs flex items-center justify-center gap-2">
                <Mail className="w-4 h-4 flex-shrink-0" />
                <span className="truncate">
                  {t.welcomeEmailNotice} {result.member.email}
                </span>
              </div>
            ) : (
              <div className="p-3 rounded-xl bg-amber-50 dark:bg-amber-950/30 border border-amber-200 dark:border-amber-500/30 text-amber-800 dark:text-amber-200 text-xs text-left">
                <div className="font-bold flex items-center gap-1.5 mb-1 text-amber-700 dark:text-amber-300">
                  <AlertCircle className="w-4 h-4 text-amber-500 flex-shrink-0" />
                  <span>ഇമെയിൽ പോയില്ല (Email Not Delivered)</span>
                </div>
                <p className="text-[11px] leading-relaxed text-amber-700/90 dark:text-amber-300/80">
                  {result.emailError || 'Render Dashboard-ൽ EMAIL_USER, EMAIL_PASS എന്നിവ കോൺഫിഗർ ചെയ്യുക.'}
                </p>
              </div>
            )}

            <button
              onClick={() => {
                setResult(null);
                setName('');
                setEmail('');
                setPhone('');
              }}
              className="w-full py-2.5 rounded-xl bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 text-slate-800 dark:text-white text-sm font-semibold transition"
            >
              {t.addAnotherMember}
            </button>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="mt-4 space-y-4">
            <div>
              <label className="block text-xs font-semibold text-slate-600 dark:text-slate-300 mb-1">
                {t.memberNameLabel}
              </label>
              <div className="relative">
                <User className="w-4 h-4 text-slate-400 absolute left-3.5 top-3.5" />
                <input
                  type="text"
                  required
                  placeholder={t.memberNamePlaceholder}
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  className="w-full pl-10 pr-4 py-2.5 bg-slate-50 dark:bg-slate-800/70 border border-slate-200 dark:border-slate-700 rounded-xl text-sm focus:outline-none focus:border-indigo-500 text-slate-900 dark:text-white placeholder-slate-400"
                />
              </div>
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-600 dark:text-slate-300 mb-1">
                {t.memberEmailLabel}
              </label>
              <div className="relative">
                <Mail className="w-4 h-4 text-slate-400 absolute left-3.5 top-3.5" />
                <input
                  type="email"
                  required
                  placeholder={t.emailPlaceholder}
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                  className="w-full pl-10 pr-4 py-2.5 bg-slate-50 dark:bg-slate-800/70 border border-slate-200 dark:border-slate-700 rounded-xl text-sm focus:outline-none focus:border-indigo-500 text-slate-900 dark:text-white placeholder-slate-400"
                />
              </div>
              <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-1">
                {t.memberEmailHelper}
              </p>
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-600 dark:text-slate-300 mb-1">
                {t.memberPhoneLabel}
              </label>
              <div className="relative">
                <Phone className="w-4 h-4 text-slate-400 absolute left-3.5 top-3.5" />
                <input
                  type="tel"
                  placeholder="+91 9876543210"
                  value={phone}
                  onChange={(e) => setPhone(e.target.value)}
                  className="w-full pl-10 pr-4 py-2.5 bg-slate-50 dark:bg-slate-800/70 border border-slate-200 dark:border-slate-700 rounded-xl text-sm focus:outline-none focus:border-indigo-500 text-slate-900 dark:text-white placeholder-slate-400"
                />
              </div>
            </div>

            <div className="pt-2">
              <button
                type="submit"
                disabled={loading}
                className="w-full py-3 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white font-bold text-sm shadow-lg shadow-indigo-600/25 transition disabled:opacity-50 flex items-center justify-center gap-2"
              >
                {loading ? t.addingMember : t.submitAddMember}
              </button>
            </div>
          </form>
        )}
      </div>
    </div>
  );
}
